const { test, expect } = require('@playwright/test')
const fs = require('node:fs')

const base = process.env.MAPPOP_TEST_URL || 'http://127.0.0.1:8787'
const token = process.env.MAPPOP_API_TOKEN || (fs.existsSync('.dev.vars') ? fs.readFileSync('.dev.vars', 'utf8').match(/^MAPPOP_API_TOKEN\s*=\s*([^\r\n]+)/m)?.[1].trim().replace(/^(["'])(.*)\1$/, '$2') : '')
const node = (page, text) => page.locator('.smm-node').filter({ hasText: text }).first()
const toolbar = (page, text) => page.locator('.toolbarBtn').filter({ hasText: new RegExp(`^${text}$`) }).first()
const saved = page => page.evaluate(() => JSON.parse(localStorage.getItem('SIMPLE_MIND_MAP_DATA')))

async function createMap(markdown) {
  const response = await fetch(`${base}/api/maps`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify({ markdown }) })
  expect(response.status).toBe(201)
  return response.json()
}
async function openEditor(page) {
  await page.goto('/')
  await expect(page.locator('.smm-node')).toHaveCount(10)
  await expect(page).toHaveTitle(/Mappop/)
  await page.waitForFunction(() => !document.querySelector('.el-loading-mask'))
}
async function editNode(page, text, replacement) {
  await node(page, text).dblclick()
  await page.locator('.ql-editor[contenteditable=true]').fill(replacement)
  await page.mouse.click(700, 860)
  await expect(node(page, replacement)).toBeVisible()
}

test('original editor: keyboard insertion, text editing, undo/redo and saved reload', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await openEditor(page)
  await node(page, 'Make room for ideas').click()
  await page.keyboard.press('Tab')
  await expect(page.locator('.smm-node')).toHaveCount(11)
  await page.locator('.ql-editor').fill('Keyboard branch 键盘分支')
  await page.mouse.click(700, 860)
  await expect(node(page, 'Keyboard branch 键盘分支')).toBeVisible()
  await expect.poll(async () => JSON.stringify(await saved(page))).toContain('Keyboard branch 键盘分支')
  await toolbar(page, 'Undo').click()
  await expect(node(page, 'Keyboard branch 键盘分支')).toHaveCount(0)
  await toolbar(page, 'Redo').click()
  await expect(node(page, 'Keyboard branch 键盘分支')).toBeVisible()
  await editNode(page, 'Make room for ideas', 'Mappop regression 回归')
  await page.keyboard.press('Control+s')
  await expect.poll(async () => (await saved(page)).root.data.text).toContain('Mappop regression')
  await page.reload()
  await expect(node(page, 'Mappop regression 回归')).toBeVisible()
  await expect(node(page, 'Keyboard branch 键盘分支')).toBeVisible()
  expect(errors).toEqual([])
})

test('original rich content: image, associative line, layout and drag', async ({ page }) => {
  await openEditor(page)
  await node(page, 'Capture a thought').click()
  await toolbar(page, 'Image').click()
  const imageDialog = page.locator('.nodeImageDialog')
  await imageDialog.locator('input.el-input__inner').first().fill('data:image/svg+xml;charset=utf-8,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="80" height="60"><rect width="80" height="60" fill="#e8624c"/><circle cx="40" cy="30" r="18" fill="#ffe8ac"/></svg>'))
  await imageDialog.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(imageDialog.locator('.el-dialog')).not.toBeVisible()
  await expect(node(page, 'Capture a thought').locator('image')).toHaveCount(1)
  await toolbar(page, 'Associative line').click()
  await node(page, 'Make it yours').click()
  await expect.poll(async () => JSON.stringify(await saved(page))).toContain('associativeLineTargets')
  const source = await node(page, 'Double-click any node to write').boundingBox()
  const destination = await node(page, 'Make it yours').boundingBox()
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height / 2, { steps: 25 })
  await page.waitForTimeout(700)
  await page.mouse.up()
  await expect.poll(async () => {
    const branch = (await saved(page)).root.children.find(item => item.data.text.includes('Make it yours'))
    return branch.children.some(item => item.data.text.includes('Double-click any node to write'))
  }).toBe(true)
  await expect(page.locator('.smm-node')).toHaveCount(10)
  await page.locator('.triggerItem').filter({ hasText: /^Structure$/ }).click()
  await page.locator('.layoutItem').first().click()
  await expect.poll(async () => (await saved(page)).layout).toBe('logicalStructure')
  await expect(page.locator('.smm-node')).toHaveCount(10)
})

test('real API: 121 Chinese nodes open, edit, persist and export through the native editor', async ({ page }, testInfo) => {
  const markdown = '# 计算机网络\n' + Array.from({ length: 12 }, (_, i) => `## 主题 ${i + 1}\n` + Array.from({ length: 9 }, (_, j) => `### 知识点 ${i + 1}.${j + 1}`).join('\n')).join('\n')
  const map = await createMap(markdown)
  expect(map.nodeCount).toBe(121)
  expect(map.url).toContain('/#/?fileURL=%2Fapi%2Fmaps%2F')
  const read = await fetch(map.markdownUrl)
  expect(read.status).toBe(200)
  expect(await read.text()).toBe(markdown)
  await page.goto(map.url)
  await expect(page.locator('.smm-node')).toHaveCount(121)
  await page.screenshot({ path: process.env.UPDATE_SCREENSHOTS === '1' ? 'docs/assets/complex-map.png' : testInfo.outputPath('complex-map.png') })
  await expect(page).not.toHaveURL(/fileURL/)
  await editNode(page, '计算机网络', '计算机网络 · 已编辑')
  await page.keyboard.press('Control+s')
  await page.reload()
  await expect(node(page, '计算机网络 · 已编辑')).toBeVisible()
  await expect(page.locator('.smm-node')).toHaveCount(121)
  await toolbar(page, 'Export').click()
  await page.locator('.downloadTypeItem').filter({ hasText: /Mappop document/ }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.locator('.nodeExportDialog').getByRole('button', { name: /^Export$/, exact: true }).click()
  const download = await downloadEvent
  const data = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
  expect(data.root.data.text).toContain('已编辑')
  const png = await page.evaluate(() => document.querySelector('.editContainer').__vue__.mindMap.export('png', false, 'Chinese map'))
  const pngBytes = Buffer.from(png.split(',')[1], 'base64')
  expect(pngBytes.subarray(1, 4).toString()).toBe('PNG')
  expect(pngBytes.length).toBeGreaterThan(100000)
  fs.writeFileSync(testInfo.outputPath('complex-chinese.png'), pngBytes)
  expect((await fetch(map.markdownUrl)).status).toBe(200)
  expect(await (await fetch(map.markdownUrl)).text()).toBe(markdown)
})

