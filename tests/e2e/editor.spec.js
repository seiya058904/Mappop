test('a newer share link supersedes a slow earlier fetch', async ({ page }) => {
  let releaseFirst
  const gate = new Promise(resolve => { releaseFirst = resolve })
  await page.route('**/delayed-a.md', async route => {
    await gate
    await route.fulfill({ contentType: 'text/markdown', body: '# Stale A\n## Must not replace B' })
  })
  await page.route('**/latest-b.md', route => route.fulfill({ contentType: 'text/markdown', body: '# Latest B\n## Correct draft' }))
  const firstRequest = page.waitForRequest('**/delayed-a.md')
  await page.goto('/#/?fileURL=%2Fdelayed-a.md')
  await firstRequest
  await page.goto('/#/?fileURL=%2Flatest-b.md')
  releaseFirst()
  const confirmation = page.getByRole('button', { name: 'Back up & open' })
  await confirmation.waitFor({ state: 'visible', timeout: 5000 }).then(() => confirmation.click()).catch(() => {})
  await expect(node(page, 'Latest B')).toBeVisible()
  await expect(node(page, 'Stale A')).toHaveCount(0)
  await expect(page.locator('.smm-node')).toHaveCount(2)
})

test('mobile shell keeps primary controls and theme selector usable', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce' })
  const page = await context.newPage()
  await page.goto(base)
  await expect(page.locator('.smm-node')).toHaveCount(4)
  expect(await page.evaluate(() => {
    const root = document.querySelector('.editContainer').__vue__.mindMap.getData()
    const count = node => 1 + (node.children || []).reduce((sum, item) => sum + count(item), 0)
    return count(root)
  })).toBe(10)
  const toolbarBox = await page.locator('.toolbar').boundingBox()
  expect(toolbarBox.x).toBeGreaterThanOrEqual(0)
  expect(toolbarBox.x + toolbarBox.width).toBeLessThanOrEqual(391)
  await toolbar(page, 'Import').tap()
  await expect(page.locator('.nodeImportDialog .el-dialog')).toBeVisible()
  await page.locator('.nodeImportDialog').getByRole('button', { name: 'Cancel', exact: true }).tap()
  await page.locator('.triggerItem').filter({ hasText: /^Themes$/ }).tap()
  await expect(page.getByRole('button', { name: /Cyber Neon/ })).toBeVisible()
  await page.getByRole('button', { name: /Cyber Neon/ }).tap()
  await expect(page.locator('#mindMapContainer')).toHaveAttribute('data-mappop-art', 'cyber-neon')
  await context.close()
})
